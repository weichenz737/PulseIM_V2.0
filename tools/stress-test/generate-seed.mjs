// Generates seed.sql (test users / conversations / friends) and users.json for the stress client.
// Usage: node generate-seed.mjs [count] [password]
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('../..', import.meta.url));
const bcrypt = require(require.resolve('bcryptjs', { paths: [root + '.tools-bcrypt/node_modules'] }));

const COUNT = Number(process.argv[2] || 2000);
const PASSWORD = process.argv[3] || 'PulseTest#2026';
const HASH = bcrypt.hashSync(PASSWORD, 10);

// High, clearly identifiable id ranges so prod data is untouched and easy to clean up.
const USER_ID_START = 9_000_001;
const CONV_ID_START = 9_000_001;

const users = [];
for (let i = 1; i <= COUNT; i++) {
  const id = USER_ID_START + i - 1;
  const peerId = i % 2 === 1 ? id + 1 : id - 1;
  const convId = CONV_ID_START + Math.floor((i - 1) / 2);
  users.push({
    id,
    phone: `199${String(i).padStart(8, '0')}`,
    nickname: `压测U${id}`,
    pulseId: `91${String(i).padStart(5, '0')}`,
    peerId,
    convId,
  });
}

const rows = (items, fn) => items.map(fn).join(',\n');

const userSql = rows(users, (u) =>
  `(${u.id}, '${u.phone}', '${HASH}', '${u.nickname}', NULL, 1, '${u.pulseId}', NOW(), NOW())`
);

const convs = [];
const members = [];
const friends = [];
for (let k = 1; k <= COUNT / 2; k++) {
  const convId = CONV_ID_START + k - 1;
  const a = users[(k - 1) * 2];
  const b = users[(k - 1) * 2 + 1];
  convs.push(`(${convId}, 1, '压测会话${convId}', NOW(), NOW())`);
  members.push(
    `(${convId}, ${a.id}, 0, FALSE, FALSE, FALSE, FALSE, ${b.id}, 'member', NOW())`,
    `(${convId}, ${b.id}, 0, FALSE, FALSE, FALSE, FALSE, ${a.id}, 'member', NOW())`
  );
  friends.push(
    `(${a.id}, ${b.id}, NOW())`,
    `(${b.id}, ${a.id}, NOW())`
  );
}

const sql = `-- PulseIM stress-test seed: ${COUNT} users / ${COUNT / 2} private conversations
-- generated by generate-seed.mjs, run inside pulse-postgres (psql -U pulse -d pulseim)
BEGIN;

INSERT INTO sys_user (id, phone, password_hash, nickname, avatar_url, status, pulse_id, created_at, updated_at)
VALUES
${userSql}
ON CONFLICT (phone) DO NOTHING;

INSERT INTO im_conversation (id, type, title, created_at, updated_at)
VALUES
${convs.join(',\n')};

INSERT INTO im_conversation_member
  (conversation_id, user_id, unread_count, mute, archived, pinned, hidden, peer_user_id, role, joined_at)
VALUES
${members.join(',\n')}
ON CONFLICT (conversation_id, user_id) DO NOTHING;

INSERT INTO im_friend (user_id, friend_id, created_at)
VALUES
${friends.join(',\n')}
ON CONFLICT (user_id, friend_id) DO NOTHING;

COMMIT;
`;

writeFileSync('seed.sql', sql);
writeFileSync('users.json', JSON.stringify(users, null, 2));
console.log(`wrote seed.sql + users.json: ${COUNT} users, ${COUNT / 2} conversations, hash=${HASH.slice(0, 7)}...`);
